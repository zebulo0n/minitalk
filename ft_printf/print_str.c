#include "ft_printf.h"

int	print_str(char *str)
{
	int	i;

	if (str == NULL)
		return (print_str("(null)"));
	i = 0;
	while (str[i])
	{
		write(1, (str + i), 1);
		i++;
	}
	return (i);
}
